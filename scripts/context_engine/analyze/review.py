"""
The fleet documentation review: every repository's documents in one place.

`fleet_health` scores repositories; this report is for reading them. For each
repository it lists every document its docs index names (path, words, the
document's own summary line), the size of the files every agent session
loads, and where the repository stands against each documentation framework
row (bamr87/bamr87 specs/DOCS.md). It is the consolidated surface a reviewer
uses to see the whole fleet's documentation without opening forty repos.

Like fleet_health it carries no timestamp: an unchanged fleet re-renders
byte-identically, and a branch name or commit is the only provenance.
"""

import re
from typing import Dict, List

from .. import ENGINE_VERSION
from .framework import words

FRAMEWORK_ROWS = (
    ("DOC-09", "UPS-DOC-09", "AGENTS.md canonical, CLAUDE.md a pointer"),
    ("DOC-10", "UPS-DOC-10", "README portfolio skeleton"),
    ("DOC-02", "UPS-DOC-02", "one H1 and a summary line per document"),
    ("DOC-03", "UPS-DOC-03", "generated docs index"),
    ("DOC-04", "UPS-DOC-04", "docs of record only at the root"),
    ("DOC-08", "UPS-DOC-08", "AGENTS.md / README.md within budget"),
    ("DOC-01", "UPS-DOC-01", "no paragraph said twice"),
)
SPEC_URL = "https://github.com/bamr87/bamr87/blob/main/specs/DOCS.md"


def _plain(summary: str) -> str:
    """Relative links in a summary point from the repo's docs/; here they would dangle."""
    return re.sub(r"\[([^\]]+)\]\((?![a-z][a-z0-9+.-]*:)[^)]*\)", r"\1", summary or "", flags=re.I)


def _cell(findings: List[Dict], check_id: str) -> str:
    hits = [f for f in findings if f["check"] == check_id]
    if not hits:
        return "✓"
    if all(f["severity"] == "info" for f in hits):
        return "~"
    return "✗"


def build_review(results: List[Dict], scope: str) -> Dict:
    """`results` as for build_report, plus `docs` (the inventory) and `sizes` per repo."""
    repos = {}
    for r in sorted(results, key=lambda x: x["name"]):
        findings = [f.to_dict() for f in r["findings"]]
        manifest = r.get("manifest") or {}
        repos[r["name"]] = {
            "repo": r["repo"], "url": r["url"], "kind": r.get("kind", "default"),
            "branch": manifest.get("default_branch", ""),
            "head": (manifest.get("head") or {}).get("sha", "")[:12],
            "error": manifest.get("error", ""),
            "sizes": r.get("sizes", {}),
            "framework": {cid: _cell(findings, cid) for cid, _, _ in FRAMEWORK_ROWS},
            "findings": [f for f in findings if f["check"].startswith("DOC-")
                         or f["severity"] in ("error", "warn")],
            "docs": [{"path": d["path"], "words": d.get("words", 0), "summary": _plain(d.get("summary", "")),
                      "source": d.get("source", "")} for d in r.get("docs", [])],
        }
    rows = {cid: sum(1 for e in repos.values() if not e["error"] and e["framework"][cid] == "✗")
            for cid, _, _ in FRAMEWORK_ROWS}
    return {
        "schema_version": "1.0",
        "engine_version": ENGINE_VERSION,
        "scope": scope,
        "summary": {
            "repositories": len(repos),
            "documents": sum(len(e["docs"]) for e in repos.values()),
            "words": sum(d["words"] for e in repos.values() for d in e["docs"]),
            "conformant": sum(1 for e in repos.values()
                              if not e["error"] and all(v != "✗" for v in e["framework"].values())),
            "failing_by_row": rows,
        },
        "repositories": repos,
    }


def sizes(source) -> Dict[str, int]:
    """Words in the files every session loads, and non-blank lines in CLAUDE.md."""
    out = {}
    for path in ("AGENTS.md", "README.md"):
        if path in source.tree_set:
            out[path] = words(source.read(path) or "")
    if "CLAUDE.md" in source.tree_set:
        out["CLAUDE.md lines"] = sum(1 for line in (source.read("CLAUDE.md") or "").splitlines() if line.strip())
    return out


def render_review(review: Dict) -> str:
    s = review["summary"]
    lines = [
        "---",
        "title: Fleet documentation review",
        "description: >-",
        "  Every repository's documents in one place, with each document's summary,",
        "  the size of the always-loaded files, and conformance to the documentation framework.",
        "generated: true",
        "---",
        "<!-- GENERATED by `python3 -m scripts.context_engine survey` - do not hand-edit -->",
        "",
        "# Fleet documentation review",
        "",
        "> Every repository's documents in one place — what each one covers, how large the files every "
        f"agent session loads are, and where each repository stands against the [documentation framework]({SPEC_URL}).",
        "",
        f"Scope: {review['scope']}. **{s['repositories']}** repositories, **{s['documents']}** indexed "
        f"documents, **{s['words']:,}** words. **{s['conformant']}** repositories meet every framework row.",
        "",
        "## Framework conformance",
        "",
        "✓ meets the row · ✗ does not · ~ informational only (or waived under Standard deviations).",
        "",
        "| Row | Requirement | Repositories failing |",
        "|---|---|---:|",
    ]
    for cid, row, text in FRAMEWORK_ROWS:
        lines.append(f"| {row} | {text} | {s['failing_by_row'].get(cid, 0)} |")
    head = " | ".join(cid for cid, _, _ in FRAMEWORK_ROWS)
    lines += ["", f"| Repository | Ref | Docs | AGENTS.md words | README.md words | CLAUDE.md lines | {head} |",
              "|---|---|---:|---:|---:|---:|" + "|".join(":-:" for _ in FRAMEWORK_ROWS) + "|"]
    for name, e in review["repositories"].items():
        if e["error"]:
            lines.append(f"| [{name}]({e['url']}) | — | — | — | — | — | " + " | ".join("—" for _ in FRAMEWORK_ROWS) + " |")
            continue
        z = e["sizes"]
        ref = f"`{e['branch']}`" + (f" @ `{e['head'][:7]}`" if e["head"] else "")
        lines.append(
            f"| [{name}]({e['url']}) | {ref} | {len(e['docs'])} | {z.get('AGENTS.md', '—')} "
            f"| {z.get('README.md', '—')} | {z.get('CLAUDE.md lines', '—')} | "
            + " | ".join(e["framework"][cid] for cid, _, _ in FRAMEWORK_ROWS) + " |")
    lines += ["", "## Repositories", ""]
    for name, e in review["repositories"].items():
        lines += [f"### {name}", ""]
        if e["error"]:
            lines += [f"Could not gather: `{e['error']}`", ""]
            continue
        lines += [f"[{e['repo']}]({e['url']}) · {e['kind']} · {len(e['docs'])} documents", ""]
        open_items = [f for f in e["findings"] if f["severity"] in ("error", "warn")]
        if open_items:
            lines += ["| Severity | Check | Finding |", "|---|---|---|"]
            for f in open_items[:12]:
                lines.append(f"| {f['severity']} | {f['check']} | {f['message'].replace('|', '/')} |")
            if len(open_items) > 12:
                lines.append(f"| … | | {len(open_items) - 12} more in docs_review.json |")
            lines.append("")
        if e["docs"]:
            lines += ["| Document | Words | What it covers |", "|---|---:|---|"]
            for d in e["docs"]:
                summary = d["summary"] or "—"
                if d["source"] in ("fallback", "none"):
                    summary = f"_no summary line_ — {summary}" if d["summary"] else "_no summary line_"
                link = f"{e['url']}/blob/{e['branch'] or 'main'}/{d['path']}"
                lines.append(f"| [`{d['path']}`]({link}) | {d['words']} | {summary} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"
